	CONTRASENA		VARCHAR(50),
	EMPRESAID		INT
)
RETURNS INT
READS SQL DATA
DETERMINISTIC
BEGIN
	DECLARE X INT;
	SET X = (SELECT COUNT(RUT) FROM USUARIO WHERE USUARIO.RUT = RUT);
