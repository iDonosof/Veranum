			USUARIO.CONTRASENA = CONTRASENA,
			USUARIO.EMPRESAID = EMPRESAID
			WHERE USUARIO.RUT = RUT;
		ELSE
			UPDATE USUARIO SET 
			USUARIO.NOMBRE = NOMBRE,
			USUARIO.APELLIDO = APELLIDO,
			USUARIO.TELEFONO = TELEFONO,
			USUARIO.DIRECCION = DIRECCION,
			USUARIO.CORREO = CORREO,
